// The pinned assets use a deliberately small XML subset: one svg and path children.
// Reject unknown markup/attributes instead of silently losing transforms, fill rules,
// strokes, references or clipping when reducing the source to path data.
function attributes(source, allowed, file) {
  const result = {};
  let cursor = 0;
  const pattern = /\s+([A-Za-z][\w:-]*)="([^"<>]*)"/gy;
  while (cursor < source.length && source.slice(cursor).trim()) {
    pattern.lastIndex = cursor;
    const match = pattern.exec(source);
    assert.ok(match, `${file}: unsupported XML attribute syntax`);
    const [, name, value] = match;
    assert.ok(allowed.includes(name), `${file}: unsupported attribute ${name}`);
    assert.ok(!Object.hasOwn(result, name), `${file}: duplicate attribute ${name}`);
    assert.ok(!value.includes('&'), `${file}: XML entities are not supported`);
    result[name] = value;
    cursor = pattern.lastIndex;
  }
  return result;
}

async function paths(name, weight) {
  const file = resolve(packageRoot, 'assets', weight, `${name}-${weight}.svg`);
  const svg = (await readFile(file, 'utf8')).trim();
  const rootMatch = /^<svg(\s[^<>]*)>([\s\S]*)<\/svg>$/.exec(svg);
  assert.ok(rootMatch, `${file}: expected a single SVG root`);
  const rootAttributes = attributes(rootMatch[1], ['xmlns', 'viewBox', 'fill'], file);
  assert.equal(rootAttributes.xmlns, 'http://www.w3.org/2000/svg', file);
  assert.equal(rootAttributes.viewBox, '0 0 256 256', file);
  assert.equal(rootAttributes.fill, 'currentColor', file);

  const children = rootMatch[2];
  const result = [];
  let cursor = 0;
  const pattern = /\s*<path(\s[^<>]*?)\s*\/>/gy;
  while (cursor < children.length && children.slice(cursor).trim()) {
    pattern.lastIndex = cursor;
    const match = pattern.exec(children);
    assert.ok(match, `${file}: only self-closing path elements are supported`);
    const path = attributes(match[1], ['d', 'opacity'], file);
    assert.ok(
      path.d && /^[Mm][MmZzLlHhVvCcSsQqTtAaEe0-9+.,\s-]*$/.test(path.d),
      `${file}: invalid path data`,
    );
    assert.ok(!path.opacity || path.opacity === '0.2', `${file}: unexpected source opacity`);
    result.push(path);
    cursor = pattern.lastIndex;
  }
  return result;
}

const icons = {};
for (const name of names) {
  const duotone = await paths(name, 'duotone');
  const bold = await paths(name, 'bold');
  assert.equal(duotone.length, 2, `${name}: expected secondary and primary duotone paths`);
  assert.equal(duotone[0].opacity, '0.2', `${name}: expected the secondary layer first`);
  assert.equal(duotone[1].opacity, undefined, `${name}: expected an opaque primary layer`);
  assert.equal(bold.length, 1, `${name}: review multiple bold paths before combining their fill geometry`);
  assert.equal(bold[0].opacity, undefined, `${name}: expected an opaque bold path`);
  icons[name] = { secondary: duotone[0].d, primary: bold[0].d };
}

