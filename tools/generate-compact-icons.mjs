const pkg = JSON.parse(
  await readFile(path.join(root, 'node_modules/@phosphor-icons/core/package.json'), 'utf8'),
);
if (pkg.version !== '2.1.1')
  throw new Error('Review icon geometry before changing @phosphor-icons/core version.');
const definitions = [];
for (const name of icons) {
  const svg = (
    await readFile(
      path.join(root, 'node_modules/@phosphor-icons/core/assets/bold', name + '-bold.svg'),
      'utf8',
    )
  ).trim();
  if (
    !svg.startsWith('<svg ') ||
    !svg.includes('viewBox="0 0 256 256"') ||
    /<(?:script|image|use)\b/.test(svg)
  )
    throw new Error('Unexpected SVG: ' + name);
  // Monochrome mask preserves the official filled outlines at every CSS size.
  const data = encodeURIComponent(svg.replace('fill="currentColor"', 'fill="black"')).replaceAll("'", '%27');
  definitions.push(
    '.pos-icon.pos-icon-' + name + ' { --pos-icon-image: url("data:image/svg+xml,' + data + '"); }',
  );
}
const css =
  `/* Generated by tools/generate-compact-icons.mjs. Phosphor Icons 2.1.1 (MIT).
 * Official Bold paths; no font synthesis or painted stroke. See third-party-licenses.txt.
 */
@layer components {
.pos-icon {
  display: inline-block;
  width: 1em;
  height: 1em;
  flex-shrink: 0;
  vertical-align: -0.125em;
  background-color: currentColor;
  mask: var(--pos-icon-image) center / contain no-repeat;
}
}
/* A mask is a foreground glyph: retain system text colors in Windows High Contrast. */
@media (forced-colors: active) {
  .pos-icon {
    forced-color-adjust: none;
    color: CanvasText;
  }
  @supports (forced-color-adjust: preserve-parent-color) {
    .pos-icon {
      forced-color-adjust: preserve-parent-color;
      color: inherit;
    }
  }
}
\n` +
  definitions.join('\n') +
  '\n';
const output = path.join(root, 'libs/ui/src/lib/compact-icons.css');
const formatted = await format(css, { ...(await resolveConfig(output)), filepath: output });
if (process.argv.includes('--check')) {
  assert.equal(await readFile(output, 'utf8'), formatted, 'Run npm run icons:generate.');
  console.log(`Verified ${icons.length} generated compact Bold icons.`);
} else {
  await writeFile(output, formatted, 'utf8');
  console.log(`Generated ${icons.length} compact Bold icons.`);
}
